"""
Title: Maximum Cooling Gap for Server Maintenance

Problem Description:
You are given a sorted list of rack positions in a data center, where each position
contains a server that must be assigned to one of two maintenance crews. To reduce
thermal interference, the company wants the minimum distance between any two servers
handled by the same crew to be as large as possible. Every server must be assigned
to exactly one of the two crews, and each crew may handle any number of servers.

Formally, given an array positions of length n in strictly increasing order, partition
the servers into two groups A and B such that for each group, the distance between
every pair of consecutive servers in that group is at least D. Your task is to compute
the maximum possible value of D for which such a partition exists.

This is a decision-and-optimization problem: for a candidate D, determine whether the
servers can be 2-colored so that no two adjacent servers in the same color class are
closer than D, then find the largest feasible D.

Return that maximum D.

Constraints:
- 2 <= n <= 2 * 10^5
- 0 <= positions[i] <= 10^18
- positions is strictly increasing
- The answer fits in a 64-bit signed integer
"""

from typing import List


class Solution:
    def max_cooling_gap(self, positions: List[int]) -> int:
        """
        Compute the maximum feasible minimum same-crew consecutive gap.

        We binary search the answer D. For each candidate D, we check whether the
        sorted positions can be partitioned into two groups so that within each group,
        consecutive chosen positions differ by at least D.

        Args:
            positions: Strictly increasing server positions.

        Returns:
            The largest integer D for which a valid 2-group partition exists.

        Time complexity:
            O(n log R), where n is the number of positions and
            R = positions[-1] - positions[0].

        Space complexity:
            O(n) for the feasibility check arrays.
        """
        n: int = len(positions)

        # The answer is at least 0 and at most the full span of the array.
        # We use a standard "find maximum feasible value" binary search.
        left: int = 0
        right: int = positions[-1] - positions[0]
        answer: int = 0

        while left <= right:
            mid: int = (left + right) // 2

            # If this candidate gap is feasible, try to make it larger.
            if self._can_partition_with_gap(positions, mid):
                answer = mid
                left = mid + 1
            else:
                # Otherwise, we must reduce the target gap.
                right = mid - 1

        return answer

    def _can_partition_with_gap(self, positions: List[int], gap: int) -> bool:
        """
        Check whether positions can be split into two groups so that each group's
        consecutive positions are at least `gap` apart.

        Core idea:
        Because positions are sorted, if two positions are closer than `gap`, they
        cannot belong to the same crew. So for each index i, all later indices j
        with positions[j] - positions[i] < gap are in conflict with i.

        Let next_bad[i] be the first index strictly after i that is NOT in conflict
        with i, i.e. the first index j such that positions[j] - positions[i] >= gap.
        Then every index in (i+1 ... next_bad[i]-1) must have the opposite color from i.

        This creates a very structured interval constraint system on a line. We solve it
        greedily using dynamic reachability of forced opposite-color intervals.

        We maintain:
        - far0: among all currently known color-0 positions, the farthest index that is
          forced to be color-1
        - far1: among all currently known color-1 positions, the farthest index that is
          forced to be color-0

        We scan left to right and track whether index i can be color 0 and/or color 1.
        If i can be color 0, then all indices in its conflict interval are forced to
        color 1, so we extend far0. Symmetrically for color 1.

        At index i:
        - color 0 is possible iff i is not inside the currently forced-to-1 region
          generated by color-1 choices, i.e. i > far1
        - color 1 is possible iff i is not inside the currently forced-to-0 region
          generated by color-0 choices, i.e. i > far0

        If neither color is possible at some index, the candidate gap is impossible.

        Args:
            positions: Strictly increasing server positions.
            gap: Candidate minimum same-crew consecutive gap.

        Returns:
            True if feasible, otherwise False.

        Time complexity:
            O(n)

        Space complexity:
            O(n) for the precomputed next_bad array.
        """
        n: int = len(positions)

        # Trivial case:
        # If gap == 0, every partition is valid because all distances are >= 0.
        if gap == 0:
            return True

        # next_ok[i] = first index j > i such that positions[j] - positions[i] >= gap.
        # Therefore, indices i+1 .. next_ok[i]-1 are too close to i and must be assigned
        # to the opposite crew if i is assigned to some crew.
        #
        # We compute this with a two-pointer sweep in O(n):
        # - r only moves forward
        # - for each i, advance r until positions[r] - positions[i] >= gap
        next_ok: List[int] = [n] * n
        r: int = 0
        for i in range(n):
            if r < i + 1:
                r = i + 1
            while r < n and positions[r] - positions[i] < gap:
                r += 1
            next_ok[i] = r

        # far0:
        #   considering all indices processed so far that could be color 0,
        #   far0 is the farthest index that is forced to be color 1.
        #
        # far1:
        #   considering all indices processed so far that could be color 1,
        #   far1 is the farthest index that is forced to be color 0.
        #
        # We use -1 to mean "no forced region yet".
        far0: int = -1
        far1: int = -1

        for i in range(n):
            # Determine whether index i can be assigned each color.
            #
            # If i <= far1, then some earlier possible color-1 position forces i to be
            # color 0, so color 1 is impossible there.
            #
            # If i <= far0, then some earlier possible color-0 position forces i to be
            # color 1, so color 0 is impossible there.
            can_be_0: bool = i > far1
            can_be_1: bool = i > far0

            # If neither color is possible, then the candidate gap cannot be achieved.
            if not can_be_0 and not can_be_1:
                return False

            # If i can be color 0, then every later index in the conflict interval
            # [i+1, next_ok[i)-1] must be color 1. So we extend far0.
            if can_be_0:
                far0 = max(far0, next_ok[i] - 1)

            # If i can be color 1, then every later index in the conflict interval
            # [i+1, next_ok[i)-1] must be color 0. So we extend far1.
            if can_be_1:
                far1 = max(far1, next_ok[i] - 1)

        # If we never got stuck, a valid coloring exists.
        return True


