/*
Title: Longest Typing Streak Within Mistake Budget
Difficulty: Medium
Topic: Sliding Window

Problem Description:
A typing practice platform stores a student's results as a binary array mistakes,
where mistakes[i] = 1 means the i-th typed word contained a mistake and mistakes[i] = 0
means it was typed correctly.

The platform wants to highlight the longest continuous streak that can be considered
"acceptable" if the student is allowed to ignore at most k mistaken words inside that streak.

Given an integer array mistakes and an integer k, return the length of the longest
contiguous subarray containing at most k values equal to 1.

In other words, we must find the maximum size of a consecutive block of words where
the number of mistakes does not exceed the allowed budget k.

Constraints:
- 1 <= mistakes.length <= 200000
- mistakes[i] is either 0 or 1
- 0 <= k <= mistakes.length

Examples:
1)
Input: mistakes = [0,1,0,0,1,0,0,0], k = 1
Output: 5

2)
Input: mistakes = [1,1,0,0,0,1,0,0,1,0], k = 2
Output: 8
*/

using System;

public class Solution
{
    /*
    Time Complexity: O(n)
    - Each element is processed by the right pointer once.
    - Each element is removed from the window by the left pointer at most once.
    - Therefore, the total work is linear in the size of the array.

    Space Complexity: O(1)
    - We only use a few integer variables.
    - No extra arrays, lists, or hash-based data structures are needed.

    Beginner-friendly idea:
    We use a "sliding window", which means we keep a current contiguous range [left..right].
    We expand the window to the right one step at a time.
    If the window becomes invalid (too many 1s), we shrink it from the left until it becomes valid again.
    At every step, we record the largest valid window length we have seen.
    */
    public int LongestAcceptableStreak(int[] mistakes, int k)
    {
        // 'left' marks the beginning of the current sliding window.
        // The window will always represent a contiguous subarray from index 'left' to index 'right'.
        int left = 0;

        // 'mistakeCount' stores how many 1s currently exist inside the window.
        // This is the key value we must control, because the problem allows at most k mistakes.
        int mistakeCount = 0;

        // 'bestLength' stores the maximum valid window length found so far.
        // We update this whenever we have a valid window and it is larger than previous answers.
        int bestLength = 0;

        // Move 'right' from the start of the array to the end.
        // At each step, we include mistakes[right] into the current window.
        for (int right = 0; right < mistakes.Length; right++)
        {
            // Step 1: Expand the window by including the new element at index 'right'.
            // If this new element is a mistake (1), then the number of mistakes in the window increases.
            if (mistakes[right] == 1)
            {
                mistakeCount++;
            }

            // Step 2: If the window now contains too many mistakes, it is invalid.
            // A valid window must satisfy: mistakeCount <= k
            //
            // So while the window is invalid, we repeatedly move 'left' forward
            // to remove elements from the beginning of the window.
            //
            // Why a while loop and not an if?
            // Because moving left once may still leave too many mistakes in the window.
            // We must keep shrinking until the window becomes valid again.
            while (mistakeCount > k)
            {
                // Before moving 'left', check whether the element leaving the window is a mistake.
                // If it is 1, then removing it decreases the mistake count.
                if (mistakes[left] == 1)
                {
                    mistakeCount--;
                }

                // Actually shrink the window by advancing the left boundary.
                left++;
            }

            // Step 3: At this point, the window [left..right] is guaranteed to be valid.
            // That means it contains at most k mistakes.
            //
            // So we compute its length and compare it with the best answer seen so far.
            int currentLength = right - left + 1;

            if (currentLength > bestLength)
            {
                bestLength = currentLength;
            }
        }

        // After checking all possible windows generated by the sliding process,
        // 'bestLength' contains the maximum valid contiguous subarray length.
        return bestLength;
    }
}

// Demo code:
