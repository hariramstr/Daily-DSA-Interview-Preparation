// call the solution method, and print the results.

var solution = new Solution();

// Example 1
int[] mistakes1 = { 0, 1, 0, 0, 1, 0, 0, 0 };
int k1 = 1;
int result1 = solution.LongestAcceptableStreak(mistakes1, k1);
Console.WriteLine(result1); // Expected: 5

